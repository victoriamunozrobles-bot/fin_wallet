import { useCallback, useEffect, useMemo, useReducer, useRef, useState } from "react";
import FinanceContext from "./FinanceContextValue";
import { initialState, makeId, monthKey, today } from "./financeUtils";
import { apiDelete, apiGet, apiPost, apiPut, ApiError } from "../services/api";

const STORAGE_KEY = "fin-wallet-state-v1";
const paymentTypeFromApi = { cash: "Efectivo", debit: "Tarjeta de débito", credit: "Tarjeta de crédito", bank: "Cuenta bancaria" };
const paymentTypeToApi = { Efectivo: "cash", "Tarjeta de débito": "debit", "Tarjeta de crédito": "credit", "Cuenta bancaria": "bank" };
const idOf = (item) => String(item?._id ?? item?.id ?? "");
const populatedName = (reference, collection) => {
  if (reference && typeof reference === "object") return reference.name ?? reference.serviceName ?? "";
  return collection.find((item) => idOf(item) === String(reference))?.name ?? "";
};
const isNetworkFailure = (error) => error instanceof ApiError && (error.status === 0 || error.status >= 500);

function fromApiState(data, previousAlerts = []) {
  const categories = data.categories.map((item) => ({
    id: idOf(item), name: item.name, type: item.type, emoji: item.icon || "✦", color: item.color || "#F3E8FF",
  }));
  const paymentMethods = data.paymentMethods.map((item) => ({
    id: idOf(item), name: item.name, type: paymentTypeFromApi[item.type] ?? item.type, icon: item.icon, color: item.color,
  }));
  const goals = data.goals.map((item) => ({
    id: idOf(item), name: item.name, target: item.targetAmount, saved: item.currentAmount, color: item.color, emoji: item.icon, deadline: item.deadline,
  }));
  const transactions = data.transactions.map((item) => {
    const type = item.type === "transfer_to_savings" ? "savings" : item.type;
    const goalName = populatedName(item.savingsGoalId, goals);
    return {
      id: idOf(item),
      type,
      amount: type === "savings" && item.transferDirection === "withdraw" ? -item.amount : item.amount,
      date: typeof item.date === "string" ? item.date.slice(0, 10) : new Date(item.date).toISOString().slice(0, 10),
      description: item.description ?? "",
      category: type === "savings" ? goalName : populatedName(item.categoryId, categories),
      categoryId: item.categoryId?._id ?? item.categoryId,
      paymentMethod: populatedName(item.paymentMethodId, paymentMethods),
      paymentMethodId: item.paymentMethodId?._id ?? item.paymentMethodId,
      goalId: item.savingsGoalId?._id ?? item.savingsGoalId,
      automaticPaymentId: item.recurringPaymentId,
      isAutoGenerated: Boolean(item.isAutoGenerated),
    };
  });
  const budgets = data.budgets.map((item) => ({
    id: idOf(item),
    category: populatedName(item.categoryId, categories),
    categoryId: item.categoryId?._id ?? item.categoryId,
    limit: item.limitAmount,
    month: item.month,
    year: item.year,
    spentAmount: item.spentAmount ?? 0,
    usagePercent: item.usagePercent ?? 0,
    alertThreshold: item.alertThreshold,
  }));
  const automaticPayments = data.automaticPayments.map((item) => ({
    id: idOf(item),
    name: item.serviceName,
    amount: item.amount,
    category: populatedName(item.categoryId, categories),
    categoryId: item.categoryId?._id ?? item.categoryId,
    paymentMethod: populatedName(item.paymentMethodId, paymentMethods),
    paymentMethodId: item.paymentMethodId?._id ?? item.paymentMethodId,
    day: item.billingDay,
    active: item.active,
    lastChargedMonth: item.lastBilledPeriod ?? "",
  }));
  const debts = data.debts.map((item) => ({
    id: idOf(item),
    direction: item.direction === "i_owe" ? "owed" : "receivable",
    name: item.personName,
    amount: item.amount,
    dueDate: item.dueDate ? new Date(item.dueDate).toISOString().slice(0, 10) : "",
    paid: item.isPaid,
    notes: item.notes,
  }));
  return {
    transactions,
    categories,
    paymentMethods,
    budgets,
    goals,
    debts,
    automaticPayments,
    alerts: previousAlerts,
    preferences: data.preferences ?? initialState.preferences,
  };
}

async function getRemoteState(previousAlerts, newCharges = [], preferences = initialState.preferences) {
  const date = new Date();
  const month = date.getMonth() + 1;
  const year = date.getFullYear();
  const [summary, transactions, categories, paymentMethods, budgets, goals, automaticPayments, debts] = await Promise.all([
    apiGet("/dashboard/summary"),
    apiGet("/transactions"),
    apiGet("/categories"),
    apiGet("/payment-methods"),
    apiGet(`/budgets?month=${month}&year=${year}`),
    apiGet("/savings-goals"),
    apiGet("/recurring-payments"),
    apiGet("/debts"),
  ]);
  if (!summary || typeof summary.availableBalance !== "number") throw new ApiError("La API devolvió un resumen financiero inválido.", 502);
  const alerts = [...(previousAlerts ?? []), ...newCharges];
  return fromApiState({ transactions, categories, paymentMethods, budgets, goals, automaticPayments, debts, preferences }, alerts.slice(0, 30));
}

function loadState() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (!saved) return initialState;
    return { ...initialState, ...JSON.parse(saved) };
  } catch (error) {
    console.error("No se pudo cargar el estado guardado de Fin Wallet.", error);
    return initialState;
  }
}

function reducer(state, action) {
  switch (action.type) {
    case "HYDRATE":
      return action.state;
    case "RESET":
      return action.state;
    case "ADD_TRANSACTION":
      return { ...state, transactions: [action.transaction, ...state.transactions] };
    case "UPDATE_TRANSACTION": {
      const previous = state.transactions.find((item) => item.id === action.transaction.id);
      const transaction = action.transaction;
      let goals = state.goals;
      if (previous?.type === "savings" && previous.goalId) {
        goals = goals.map((goal) => goal.id === previous.goalId ? { ...goal, saved: goal.saved - previous.amount } : goal);
      }
      if (transaction.type === "savings" && transaction.goalId) {
        goals = goals.map((goal) => goal.id === transaction.goalId ? { ...goal, saved: goal.saved + transaction.amount } : goal);
      }
      return { ...state, goals, transactions: state.transactions.map((item) => item.id === transaction.id ? transaction : item) };
    }
    case "DELETE_TRANSACTION": {
      const transaction = state.transactions.find((item) => item.id === action.id);
      const goals = transaction?.type === "savings" && transaction.goalId
        ? state.goals.map((goal) => goal.id === transaction.goalId ? { ...goal, saved: goal.saved - transaction.amount } : goal)
        : state.goals;
      return { ...state, goals, transactions: state.transactions.filter((item) => item.id !== action.id) };
    }
    case "SET_COLLECTION":
      return { ...state, [action.collection]: action.items };
    case "SET_PREFERENCES":
      return { ...state, preferences: { ...state.preferences, ...action.preferences } };
    case "ADD_ALERT":
      return { ...state, alerts: [action.alert, ...state.alerts].slice(0, 30) };
    case "PROCESS_AUTOMATIC_PAYMENTS": {
      const currentMonth = monthKey(action.date);
      const day = Number(action.date.slice(8, 10));
      const due = state.automaticPayments.filter((payment) => payment.active !== false && Number(payment.day) <= day && payment.lastChargedMonth !== currentMonth);
      if (!due.length) return state;
      const newTransactions = due.map((payment) => ({
        id: makeId(), type: "expense", amount: Number(payment.amount), date: action.date,
        category: payment.category, paymentMethod: payment.paymentMethod,
        description: `${payment.name} · pago automático`, automaticPaymentId: payment.id, isAutoGenerated: true,
      }));
      const newAlerts = due.map((payment) => ({
        id: makeId(), kind: "automatic", message: `Se registró el pago de ${payment.name} por ${payment.amount}.`, date: action.date,
      }));
      return {
        ...state,
        transactions: [...newTransactions, ...state.transactions],
        automaticPayments: state.automaticPayments.map((payment) => due.some((item) => item.id === payment.id) ? { ...payment, lastChargedMonth: currentMonth } : payment),
        alerts: [...newAlerts, ...state.alerts].slice(0, 30),
      };
    }
    default:
      return state;
  }
}

function toApiTransaction(data, state) {
  const transaction = { ...data };
  const type = transaction.type === "savings" ? "transfer_to_savings" : transaction.type;
  const category = state.categories.find((item) => item.name === transaction.category);
  const method = state.paymentMethods.find((item) => item.name === transaction.paymentMethod);
  const goal = state.goals.find((item) => item.id === transaction.goalId || item.name === transaction.category);
  const payload = {
    type,
    amount: Math.abs(Number(transaction.amount)),
    date: transaction.date || today(),
    description: transaction.description ?? "",
    isAutoGenerated: Boolean(transaction.isAutoGenerated),
  };
  if (transaction.categoryId || category?.id) payload.categoryId = transaction.categoryId || category.id;
  if (transaction.paymentMethodId || method?.id) payload.paymentMethodId = transaction.paymentMethodId || method.id;
  if (type === "transfer_to_savings") {
    payload.savingsGoalId = transaction.goalId || goal?.id;
    payload.transferDirection = Number(transaction.amount) < 0 ? "withdraw" : "deposit";
  } else if (transaction.id) {
    payload.savingsGoalId = null;
  }
  return payload;
}

function resourcePayload(collection, item, state) {
  if (collection === "categories") return { name: item.name, type: item.type, icon: item.emoji || item.icon || "✦", color: item.color, isCustom: item.isCustom ?? true };
  if (collection === "paymentMethods") return { name: item.name, type: paymentTypeToApi[item.type] ?? item.type, icon: item.icon || "▣", color: item.color || "#F3E8FF" };
  if (collection === "budgets") {
    const category = state.categories.find((entry) => entry.name === item.category || idOf(entry) === String(item.categoryId));
    const now = new Date();
    return { categoryId: item.categoryId || category?.id, limitAmount: Number(item.limit), month: Number(item.month) || now.getMonth() + 1, year: Number(item.year) || now.getFullYear(), alertThreshold: Number(item.alertThreshold) || state.preferences.threshold || 80 };
  }
  if (collection === "goals") return { name: item.name, targetAmount: Number(item.target), icon: item.emoji || item.icon || "✿", color: item.color || "#FF4D8D", ...(item.deadline ? { deadline: item.deadline } : {}) };
  if (collection === "debts") return { direction: item.direction === "owed" ? "i_owe" : "owed_to_me", personName: item.name, amount: Number(item.amount), ...(item.dueDate ? { dueDate: item.dueDate } : {}), isPaid: Boolean(item.paid), notes: item.notes || "" };
  if (collection === "automaticPayments") {
    const category = state.categories.find((entry) => entry.name === item.category || idOf(entry) === String(item.categoryId));
    const method = state.paymentMethods.find((entry) => entry.name === item.paymentMethod || idOf(entry) === String(item.paymentMethodId));
    return { serviceName: item.name, amount: Number(item.amount), categoryId: item.categoryId || category?.id, paymentMethodId: item.paymentMethodId || method?.id, billingDay: Number(item.day), active: item.active !== false, lastBilledPeriod: item.lastChargedMonth || "" };
  }
  return item;
}

const collectionPaths = {
  categories: "/categories",
  paymentMethods: "/payment-methods",
  budgets: "/budgets",
  goals: "/savings-goals",
  debts: "/debts",
  automaticPayments: "/recurring-payments",
};

export function FinanceProvider({ children }) {
  const [state, dispatch] = useReducer(reducer, undefined, loadState);
  const stateRef = useRef(state);
  const [storageMode, setStorageMode] = useState("connecting");
  const [apiError, setApiError] = useState("");

  useEffect(() => { stateRef.current = state; }, [state]);
  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
    } catch (error) {
      console.error("No se pudo guardar el estado de Fin Wallet.", error);
    }
  }, [state]);

  const syncRemoteState = useCallback(async (extraAlerts = []) => {
    const remote = await getRemoteState([...stateRef.current.alerts], extraAlerts, stateRef.current.preferences);
    dispatch({ type: "HYDRATE", state: remote });
    return remote;
  }, []);

  useEffect(() => {
    let active = true;
    const bootstrap = async () => {
      try {
        await apiGet("/health");
        const due = await apiPost("/recurring-payments/process-due", {});
        const alerts = (due?.charged ?? []).map((item) => ({
          id: `charge-${idOf(item)}`,
          kind: "automatic",
          message: `Se registró el pago automático ${item.description}.`,
          date: today(),
        }));
        const remote = await getRemoteState(stateRef.current.alerts, alerts, stateRef.current.preferences);
        if (active) {
          dispatch({ type: "HYDRATE", state: remote });
          setStorageMode("api");
          setApiError("");
        }
      } catch (error) {
        if (active) {
          setStorageMode("local");
          if (!isNetworkFailure(error)) {
            setApiError(error.message);
            console.error("No se pudo sincronizar Fin Wallet con la API.", error);
          }
        }
      }
    };
    bootstrap();
    return () => { active = false; };
  }, []);

  const runMutation = useCallback(async (remoteWork, localWork) => {
    if (storageMode !== "api") {
      return localWork() !== false;
    }
    try {
      const result = await remoteWork();
      await syncRemoteState(result?.alerts ?? []);
      setApiError("");
      return true;
    } catch (error) {
      if (isNetworkFailure(error)) {
        setStorageMode("local");
        const localResult = localWork();
        setApiError("");
        return localResult !== false;
      }
      setApiError(error.message);
      console.error("La API rechazó una operación de Fin Wallet.", error);
      return false;
    }
  }, [storageMode, syncRemoteState]);

  const addTransaction = useCallback((data) => runMutation(
    () => apiPost("/transactions", toApiTransaction(data, stateRef.current)),
    () => dispatch({ type: "ADD_TRANSACTION", transaction: { ...data, id: makeId(), amount: Number(data.amount) } }),
  ), [runMutation]);

  const updateTransaction = useCallback((data) => runMutation(
    () => apiPut(`/transactions/${encodeURIComponent(data.id)}`, toApiTransaction(data, stateRef.current)),
    () => dispatch({ type: "UPDATE_TRANSACTION", transaction: { ...data, amount: Number(data.amount) } }),
  ), [runMutation]);

  const deleteTransaction = useCallback((id) => runMutation(
    () => apiDelete(`/transactions/${encodeURIComponent(id)}`),
    () => dispatch({ type: "DELETE_TRANSACTION", id }),
  ), [runMutation]);

  const addSavings = useCallback((goalId, amount, date = today(), description = "Aporte a meta") => {
    const goal = stateRef.current.goals.find((item) => item.id === goalId);
    if (!goal || Number(amount) <= 0) return Promise.resolve(false);
    return runMutation(
      () => apiPost(`/savings-goals/${encodeURIComponent(goalId)}/deposit`, { amount: Number(amount), date, description }),
      () => {
        const current = stateRef.current;
        const available = current.transactions.filter((item) => item.type === "income").reduce((sum, item) => sum + Number(item.amount), 0)
          - current.transactions.filter((item) => item.type === "expense").reduce((sum, item) => sum + Number(item.amount), 0)
          - current.goals.reduce((sum, item) => sum + Number(item.saved), 0);
        if (Number(amount) > available) return false;
        dispatch({ type: "SET_COLLECTION", collection: "goals", items: current.goals.map((item) => item.id === goalId ? { ...item, saved: item.saved + Number(amount) } : item) });
        dispatch({ type: "ADD_TRANSACTION", transaction: { id: makeId(), type: "savings", amount: Number(amount), date, category: goal.name, goalId, paymentMethod: "Ahorros", description } });
        return true;
      },
    );
  }, [runMutation]);

  const withdrawSavings = useCallback((goalId, amount, date = today()) => {
    const goal = stateRef.current.goals.find((item) => item.id === goalId);
    if (!goal || Number(amount) <= 0) return Promise.resolve(false);
    return runMutation(
      () => apiPost(`/savings-goals/${encodeURIComponent(goalId)}/withdraw`, { amount: Number(amount), date }),
      () => {
        const current = stateRef.current;
        const currentGoal = current.goals.find((item) => item.id === goalId);
        if (!currentGoal || Number(amount) > currentGoal.saved) return false;
        dispatch({ type: "SET_COLLECTION", collection: "goals", items: current.goals.map((item) => item.id === goalId ? { ...item, saved: item.saved - Number(amount) } : item) });
        dispatch({ type: "ADD_TRANSACTION", transaction: { id: makeId(), type: "savings", amount: -Number(amount), date, category: goal.name, goalId, paymentMethod: "Ahorros", description: "Retiro de meta" } });
        return true;
      },
    );
  }, [runMutation]);

  const setCollection = useCallback((collection, items) => {
    const path = collectionPaths[collection];
    const previousItems = stateRef.current[collection] ?? [];
    if (!path) {
      dispatch({ type: "SET_COLLECTION", collection, items });
      return Promise.resolve(true);
    }
    const localWork = () => dispatch({ type: "SET_COLLECTION", collection, items });
    if (storageMode !== "api") {
      localWork();
      return Promise.resolve(true);
    }
    const byId = new Map(previousItems.map((item) => [idOf(item), item]));
    const nextById = new Map(items.map((item) => [idOf(item), item]));
    const operations = [];
    for (const previous of previousItems) {
      if (!nextById.has(idOf(previous))) operations.push(() => apiDelete(`${path}/${encodeURIComponent(idOf(previous))}`));
    }
    for (const item of items) {
      const id = idOf(item);
      const payload = resourcePayload(collection, item, stateRef.current);
      if (byId.has(id)) operations.push(() => apiPut(`${path}/${encodeURIComponent(id)}`, payload));
      else operations.push(() => apiPost(path, payload));
    }
    return runMutation(async () => {
      for (const operation of operations) await operation();
    }, localWork);
  }, [runMutation, storageMode]);

  const setPreferences = useCallback((preferences) => dispatch({ type: "SET_PREFERENCES", preferences }), []);
  const addAlert = useCallback((alert) => dispatch({ type: "ADD_ALERT", alert: { ...alert, id: makeId(), date: today() } }), []);

  const processAutomaticPayments = useCallback((date = today()) => {
    const localWork = () => dispatch({ type: "PROCESS_AUTOMATIC_PAYMENTS", date });
    return runMutation(
      async () => {
        const result = await apiPost("/recurring-payments/process-due", { date });
        const alerts = (result?.charged ?? []).map((item) => ({
          id: `charge-${idOf(item)}`, kind: "automatic", message: `Se registró el pago automático ${item.description}.`, date,
        }));
        return { alerts };
      },
      localWork,
    );
  }, [runMutation]);

  const simulateRecurringPayment = useCallback((payment) => {
    const localWork = () => {
      if (payment.lastChargedMonth === monthKey()) return;
      dispatch({ type: "ADD_TRANSACTION", transaction: {
        id: makeId(), type: "expense", amount: Number(payment.amount), date: today(), category: payment.category,
        paymentMethod: payment.paymentMethod, description: `${payment.name} · pago automático`,
        automaticPaymentId: payment.id, isAutoGenerated: true,
      } });
      dispatch({ type: "SET_COLLECTION", collection: "automaticPayments", items: stateRef.current.automaticPayments.map((item) => item.id === payment.id ? { ...item, lastChargedMonth: monthKey() } : item) });
      dispatch({ type: "ADD_ALERT", alert: { id: makeId(), kind: "automatic", message: `Se registró el pago de ${payment.name}.`, date: today() } });
    };
    return runMutation(
      async () => {
        const transaction = await apiPost(`/recurring-payments/${encodeURIComponent(payment.id)}/simulate`, {});
        return { alerts: [{
          id: `charge-${idOf(transaction)}`, kind: "automatic", message: `Se registró el pago automático ${transaction.description}.`, date: today(),
        }] };
      },
      localWork,
    );
  }, [runMutation]);

  const resetDemoData = useCallback(() => runMutation(
    () => apiPost("/seed/reset"),
    () => dispatch({ type: "RESET", state: structuredClone(initialState) }),
  ), [runMutation]);

  const totals = useMemo(() => {
    const totalIncome = state.transactions.filter((item) => item.type === "income").reduce((sum, item) => sum + Number(item.amount), 0);
    const totalExpenses = state.transactions.filter((item) => item.type === "expense").reduce((sum, item) => sum + Number(item.amount), 0);
    const totalSavings = state.goals.reduce((sum, item) => sum + Number(item.saved), 0);
    return { totalIncome, totalExpenses, totalSavings, available: totalIncome - totalExpenses - totalSavings };
  }, [state.transactions, state.goals]);

  const value = useMemo(() => ({
    ...state,
    ...totals,
    storageMode,
    apiError,
    addTransaction,
    updateTransaction,
    deleteTransaction,
    addSavings,
    withdrawSavings,
    setCollection,
    setPreferences,
    addAlert,
    processAutomaticPayments,
    simulateRecurringPayment,
    resetDemoData,
  }), [
    state, totals, storageMode, apiError, addTransaction, updateTransaction, deleteTransaction,
    addSavings, withdrawSavings, setCollection, setPreferences, addAlert, processAutomaticPayments,
    simulateRecurringPayment, resetDemoData,
  ]);

  return <FinanceContext.Provider value={value}>{children}</FinanceContext.Provider>;
}
