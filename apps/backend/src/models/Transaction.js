import mongoose from "mongoose";

const transactionSchema = new mongoose.Schema({
  userId: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true, index: true },
  type: { type: String, enum: ["income", "expense", "transfer_to_savings"], required: true, index: true },
  amount: { type: Number, required: true, min: 0.01 },
  date: { type: Date, required: true, index: true },
  description: { type: String, trim: true, maxlength: 200, default: "" },
  categoryId: { type: mongoose.Schema.Types.ObjectId, ref: "Category" },
  paymentMethodId: { type: mongoose.Schema.Types.ObjectId, ref: "PaymentMethod" },
  savingsGoalId: { type: mongoose.Schema.Types.ObjectId, ref: "SavingsGoal" },
  transferDirection: { type: String, enum: ["deposit", "withdraw"], default: "deposit" },
  isAutoGenerated: { type: Boolean, default: false },
}, { timestamps: true });

transactionSchema.index({ date: -1, type: 1 });
transactionSchema.index({ categoryId: 1, date: -1 });
transactionSchema.index({ paymentMethodId: 1, date: -1 });

export default mongoose.models.Transaction ?? mongoose.model("Transaction", transactionSchema);
